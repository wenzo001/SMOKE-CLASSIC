/* 当前称号索引（累计根数 → 档位） */
function titleOf(total){
  let t = 0;
  for(let i=0;i<TITLES.length;i++) if(total >= TITLES[i].c) t = i;
  return t;
}
/* 距下一级还差多少根；已满级返回 0 */
function titleNext(total){
  const t = titleOf(total);
  if(t >= TITLES.length-1) return 0;
  return TITLES[t+1].c - total;
}
